#!/bin/bash
#SBATCH --job-name=data_stage_e
#SBATCH --partition=hx1-16   # edit for your cluster
#SBATCH --nodes=1   # edit for your cluster
#SBATCH --ntasks=1
#SBATCH --cpus-per-task=2
#SBATCH --mem=8G
#SBATCH --output=logs/stage_e_%j.out   # edit for your cluster (relative to the submit directory)
#SBATCH --error=logs/stage_e_%j.err   # edit for your cluster (relative to the submit directory)
# Stage E production (stages E-1 to E-7): split -> stats -> manifests -> precheck -> write_configs --production
#   -> check of the num_atoms distribution JSON -> dataset regression -> check_data_rebuild.py --stage E.
# Input: RUN/results/gamma_dedup.csv (output of stage D2). Stops immediately if absent (gamma_all.csv is not substituted).
# Order: split -> stats -> manifests -> baseline_csv -> precheck -> write_configs -> num_atoms check -> dataset_regression -> check_data_rebuild E -> manifests_check -> configs_check.
# The outputs are the production RUN/results/ (each stage_e_*.py raises an exception if a file exists. No --force is given) and the 3 new yaml files of MN/mattergen/conf and the 4 sbatch files of RUN/scripts
#   written by write_configs --production.
# The addition of AL_S5_210_TRAIN to num_atoms_distribution.py of MN is not done by this script (done separately using the block of num_atoms_dist_train.json).
set -euo pipefail
PY=${MACE_PY}          # Transcribed from: tmp/sbatch_e_test.sh:13
MNPY=${GEN_PY}           # Transcribed from: tmp/sbatch_e_test.sh:14 (for a check that imports the dataset)
MNROOT=${GBREL_CODE}
export PYTHONDONTWRITEBYTECODE=1 OMP_NUM_THREADS=1
unset DATA_RESULTS_DIR                                         # make sure it is never switched to anything other than the production RUN/results
RUN=${GBREL_WORK}/workspace/experiments/data_rebuild
RES=$RUN/results; VER=$RUN/verification
cd "$RUN/scripts"
echo "host=$(hostname) job=${SLURM_JOB_ID:-} start=$(date -u +%FT%TZ)"

# ---- guard: existence of the inputs (no silent fallback) ----
if [ ! -s "$RES/gamma_dedup.csv" ]; then
  echo "FATAL: $RES/gamma_dedup.csv does not exist (stage D2 not finished). It is not substituted by gamma_all.csv" >&2
  exit 2
fi
for f in template_map.csv bulk_membership.csv; do
  [ -s "$RES/$f" ] || { echo "FATAL: $RES/$f does not exist" >&2; exit 2; }
done
"$PY" -c "import pymatgen, ase, yaml, numpy, scipy" || { echo "FATAL: mace-mh import" >&2; exit 1; }

echo "=== E-1 split"
"$PY" stage_e_split.py --results-dir "$RES"                     # the 31 templates of template_map.csv (--templates-from-csv is not given)

echo "=== E-3 stats"
"$PY" stage_e_stats.py --results-dir "$RES"                     # dxvpsde_stats / num_atoms_dist / average_density / eval_targets

echo "=== E-4 manifests"
# --cnids omitted = all 31 templates of template_map.csv
PYTHONPATH=$MNROOT "$PY" stage_e_manifests.py --results-dir "$RES"

echo "=== E-6 baseline_csv"
# The default output destination is MN/datasets/csv/scm_al_baseline/{train,val,test}.csv (build_tilt_baseline_csv.py:34.
# Same as CSV_DIR of sbatch_prep_cache_baseline.sh of write_configs). pymatgen only, so the evaluation environment.
"$PY" build_tilt_baseline_csv.py --results-dir "$RES"

echo "=== E-7 precheck"
# The dataset is imported, so the venv of MN. By specification all rows are printed without stopping at failing rows (the count and the list are returned to the parent).
PYTHONPATH=$MNROOT "$MNPY" stage_e_precheck.py --results-dir "$RES" 2>&1 | tee "$VER/E-precheck.log"
"$PY" - "$RES/precheck_summary.json" <<'PYEOF'
import json, sys
s = json.load(open(sys.argv[1]))
print(f"PRECHECK n_rows_total={s['n_rows_total']} n_failed_total={s['n_failed_total']} (if not 0 the count and the list precheck_rows.csv are returned to the parent)")
PYEOF

echo "=== E-5/E-6 write_configs --production"
"$PY" stage_e_write_configs.py --production --results-dir "$RES"   # input to the next stage

echo "=== check of the num_atoms distribution JSON (num_atoms_dist_train.json of E-3. It is generated by stats)"
"$PY" - "$RES/num_atoms_dist_train.json" "$RES/split.json" <<'PYEOF'
import json, sys
d = json.load(open(sys.argv[1])); sp = json.load(open(sys.argv[2]))
assert d["n_train"] == sp["n_train"], (d["n_train"], sp["n_train"])
assert sum(e["count"] for e in d["entries"]) == d["n_train"]
assert abs(sum(e["p"] for e in d["entries"]) - 1.0) < 1e-12
assert not d["natoms_outside_allowed"], d["natoms_outside_allowed"]
assert "AL_S5_210_TRAIN" in d["num_atoms_distribution_py_block"]
print("NUM_ATOMS_JSON OK n_train=%d support=%s" % (d["n_train"], d["support"]))
PYEOF

echo "=== dataset.py regression (dataset.py before the modification = the committed version)"
BEFORE=$VER/dataset_before_2162ab4.py
[ ! -e "$BEFORE" ] || { echo "FATAL: $BEFORE already exists (not overwritten)" >&2; exit 2; }
git -C "$MNROOT" show 2162ab4:mattergen/symmetry_constrained/variable_length/dataset.py > "$BEFORE"
# must be identical to the HEAD snapshot used in the small test (tmp/e_test/dataset_before_HEAD.py)
[ "$(sha256sum "$BEFORE" | cut -d' ' -f1)" = "f322ce1cfa5800a977e723c898b01907ead97407c03fc84b35aa82495682dc44" ] \
  || { echo "FATAL: the sha256 of dataset.py before the modification differs from the expected one" >&2; exit 2; }
PYTHONPATH=$MNROOT "$MNPY" dataset_regression.py --new-json "$RES/split.json" --before-module "$BEFORE" \
    --out "$VER/dataset_regression.json" 2>&1 | tee "$VER/check-9_dataset_regression.log"

echo "=== check_data_rebuild --stage E"
"$PY" check_data_rebuild.py --stage E --results-dir "$RES" --expect-n-templates 31 --regression-json "$VER/dataset_regression.json"

echo "=== manifests_check"
"$PY" check_e_manifests.py --results-dir "$RES" --log "$VER/check-E_manifests.log"

echo "=== configs_check (check of the production output. check_e_configs.py requires out/mattergen/conf and out/scripts, so a staging of links is made)"
CK=$RUN/tmp/configs_check_root
[ ! -e "$CK" ] || { echo "FATAL: $CK already exists (not overwritten)" >&2; exit 2; }
mkdir -p "$CK"
ln -s "$MNROOT/mattergen" "$CK/mattergen"
ln -s "$RUN/scripts" "$CK/scripts"
PYTHONPATH=$MNROOT "$MNPY" check_e_configs.py --out-dir "$CK" --results-dir "$RES" --log "$VER/E-configs.log"

echo "STAGE_E_DONE end=$(date -u +%FT%TZ)"
