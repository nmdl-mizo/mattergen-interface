def in_plane_area_bc(atoms) -> float:
    cell = np.array(atoms.get_cell())
    return float(np.linalg.norm(np.cross(cell[1], cell[2])))


def min_dist_mic(atoms) -> float:
    cell = np.array(atoms.get_cell())
    frac = np.array(atoms.get_scaled_positions(wrap=True))
    n = frac.shape[0]
    shifts = np.array([[i, j, k] for i in (-1, 0, 1) for j in (-1, 0, 1) for k in (-1, 0, 1)])
    min_d = np.inf
    for s in range(0, n, 60):
        block = frac[s:s + 60]
        for shift in shifts:
            d = block[:, None, :] - frac[None, :, :] + shift[None, None, :]
            dc = d @ cell
            dist = np.linalg.norm(dc, axis=-1)
            if np.all(shift == 0):
                idx = np.arange(block.shape[0])
                dist[idx, s + idx] = np.inf
            m = dist.min()
            if m < min_d:
                min_d = m
    return float(min_d)
