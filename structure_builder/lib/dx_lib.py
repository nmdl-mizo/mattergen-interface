def dx_tag(dx: float) -> str:
    sign = "p" if dx >= 0 else "m"
    return f"dx_{sign}{abs(dx):.3f}"


def pilot_poscar_path(cnid: str, k: int, seed: int) -> Path:
    raise NotImplementedError("pilot_poscar_path read the internal pilot run directory; it is not part of the public release")


def apply_dx_transform(atoms, dx: float):
    """Rigid transformation: grain 1 fixed, grain 2 +dx (Cartesian x), cell a-axis length +2dx. Returns new Atoms (non-destructive)."""
    new_atoms = atoms.copy()
    frac = np.array(atoms.get_scaled_positions(wrap=True))
    grain2_mask = frac[:, 0] >= 0.5
    pos = np.array(atoms.get_positions())
    pos[grain2_mask, 0] += dx
    cell = np.array(atoms.get_cell())
    new_cell = cell.copy()
    new_cell[0, 0] += 2.0 * dx
    new_atoms.set_cell(new_cell, scale_atoms=False)
    new_atoms.set_positions(pos)
    return new_atoms, int(grain2_mask.sum()), int((~grain2_mask).sum())


def build_dx_asbuilt(cnid: str, k: int, seed: int, dx: float):
    """Reads the as-built pilot (dx=0) of (cnid,k,seed) and returns Atoms with dx applied."""
    src = pilot_poscar_path(cnid, k, seed)
    atoms = ase_read(str(src), format="vasp")
    new_atoms, n_g2, n_g1 = apply_dx_transform(atoms, dx)
    return new_atoms, src, n_g1, n_g2


def build_dx_pure_template(cnid: str, dx: float):
    """Atoms with dx applied to the as-built pilot of k=0 (pure GB, no removal) (only for the template of the role assignment)."""
    return build_dx_asbuilt(cnid, 0, 0, dx)


def fit_template_bulk(atoms):
    """Performs the same logic as build_bulk_membership.build_template_bulk() with an Atoms object as direct input.
    Returns the fractional reference coordinates and indices of the assignment targets (bulkA/bulkB)."""
    cell = np.array(atoms.get_cell())
    frac = np.array(atoms.get_scaled_positions(wrap=True))

    res = audit_symmetry(atoms, normal_axis=BM.NORMAL_AXIS, use_v2_candidates=True,
                          force_r_name=BM.FORCE_R_NAME)
    op_residual = res["max_residual_A"]
    if not (op_residual < BM.FIT_RESIDUAL_TOL_A):
        raise RuntimeError(f"symmetry fit residual too large: {op_residual:.3e}A")
    R = _r_candidates_v2(BM.NORMAL_AXIS)[BM.FORCE_R_NAME]
    t = np.array(res["best_t"], dtype=float)

    grainA_idx = np.where((frac[:, 0] > 0.0) & (frac[:, 0] < 0.5))[0]
    dist_center = np.abs(frac[grainA_idx, 0] - 0.25)
    order = np.argsort(dist_center, kind="stable")
    bulkA_idx = grainA_idx[order[:BM.N_BULK]]

    moved = _apply_op(frac[bulkA_idx], R, t)
    d = BM._mic_pairwise_dist(cell, moved, frac)
    bulkB_idx = np.argmin(d, axis=1)
    bulkB_image_dist = d[np.arange(len(bulkA_idx)), bulkB_idx]
    dup = len(set(bulkB_idx.tolist())) != BM.N_BULK

    return {
        "cell": cell,
        "bulkA_idx": bulkA_idx,
        "bulkB_idx": bulkB_idx,
        "bulkA_frac": frac[bulkA_idx].copy(),
        "bulkB_frac": frac[bulkB_idx].copy(),
        "op_residual_A": float(op_residual),
        "bulkB_duplicate_at_build": bool(dup),
        "bulkB_image_dist_max_A": float(bulkB_image_dist.max()),
    }


