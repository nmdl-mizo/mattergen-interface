#!/usr/bin/env python3
"""
dx_lib.py -- shared library of dx (rigid translation along the GB normal).

Specification: dx-stratified sweep.

Definition of the dx operation (verified by measurement):
  For the existing 410 as-built inputs (atom removal, dx=0 fixed),
    - atoms of grain 1 (fractional x<0.5, decided in the cell of dx=0): the Cartesian positions are not changed at all
    - atoms of grain 2 (fractional x>=0.5): only the Cartesian x coordinate is shifted by +dx
    - cell: only cell[0][0] (length of the a axis) is increased by 2*dx. cell[0][1], cell[0][2], cell[1], cell[2] are unchanged
  This rigid transformation was adopted after verifying that it is exactly identical to the structure generated by itf.get_bicrystal(dx=dx) of scripts/config/01_build_all.py
  (measured: for cnid_1_0, dx=0.75 the Cartesian difference < 1e-14 A and the off-diagonal components of the cell difference
  < 1e-15 A).

  Reason for choosing this method (author's choice, to be reported):
  The specification says "the construction follows the same protocol as 01_build_all.py; only dx=0.0 is replaced by the swept values",
  but 01_build_all.py itself does not implement any removal (k>0) (the removal is done by a separate pipeline,
  removal_builder.py of the atom removal). There are two conceivable ways to apply dx to the structures after the removal:
  
    (A) apply the above rigid transformation afterwards to the as-built dx=0 structures with the removal already done (the inputs of the existing 410 structures themselves).
        
    (B) for each dx, rebuild the k=0 structure with itf.get_bicrystal(dx=dx) and rerun remove_symmetric_pairs()
        with the same seed each time to remove the atoms.
  (B) moves the removal-candidate window (fractional x in [0.45,0.55]) with the dx shift, so for large dx
  different physical atoms can be removed even with "the same seed" (the identity of the removed atoms depends on dx).
  This contradicts "only dx may be changed" of the specification. (A) can apply only the rigid translation while keeping the removal identity strictly fixed,
  and satisfies "only dx may be changed" most faithfully. Moreover (A) was confirmed by measurement to be numerically identical to the output of the 01_build_all.py type of construction
  (stated in the docstring of this file
  and in the final report). Therefore (A) was adopted.
"""
